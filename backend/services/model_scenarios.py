SCENARIO_GROUP_KEYS = tuple(item["groupKey"] for item in _SCENARIO_GROUPS)

_MODEL_TO_GROUP = {
    model_key: group["groupKey"]
    for group in _SCENARIO_GROUPS
    for model_key in group["modelKeys"]
}


def list_scenario_groups(phase: int | None = None) -> list[dict]:
    """Return merged same-task scenario groups for the application catalog."""
    groups = []
    for group in _SCENARIO_GROUPS:
        models = []
        for model_key in group["modelKeys"]:
            scenario = get_scenario(model_key)
            if scenario is None:
                continue
            if phase is not None and scenario["phase"] != phase:
                continue
            models.append(scenario)
        if not models:
            continue
        item = deepcopy(group)
        item["models"] = models
        item["phases"] = sorted({model["phase"] for model in models})
        item["phase"] = min(item["phases"])
        item["defaultModelKey"] = models[0]["modelKey"]
        item["modelCount"] = len(models)
        groups.append(item)
    return groups


def get_scenario_group(group_key: str) -> dict | None:
    """Return one merged scenario group by groupKey."""
    for group in list_scenario_groups():
        if group["groupKey"] == group_key:
            return group
    return None


def resolve_group_key(model_or_group_key: str) -> str | None:
    """Map a legacy modelKey or current groupKey to a groupKey."""
    if model_or_group_key in SCENARIO_GROUP_KEYS:
        return model_or_group_key
    return _MODEL_TO_GROUP.get(model_or_group_key)
